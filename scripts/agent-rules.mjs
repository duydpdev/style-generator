/**
 * How `documents/agent-contract.md` becomes the rules file `style-gen init`
 * writes to `.claude/rules/style-generator.md` (shared by
 * `emit-agent-rules.mjs` and its test, so the build and its check agree).
 *
 * The file lives in the consumer's app, not in this repository, so:
 * - the docs-script markers (`<!-- embed: … -->`, `<!-- signature: … -->`,
 *   `<!-- snippet: … -->` and their closers) are dropped; the fenced blocks
 *   they filled stay;
 * - relative links become GitHub blob URLs at the release tag `v<version>`
 *   (semantic-release's default tag format), so they show the docs of the
 *   installed version; resolved from the contract's own repo path;
 * - two header comments stamp the package version and tell the app to keep
 *   Tailwind from scanning the file (it holds example class literals).
 */

/** The repository's blob URLs; a ref (`v<version>`) and a path follow. */
export const REPO_BLOB_URL =
  "https://github.com/duydpdev/style-generator/blob/";

/** A docs-script marker on a line of its own, plus the blank line after it. */
const MARKER_LINE_RE =
  /^<!-- \/?(?:embed|signature|snippet)\b[^\n]*-->\n(?:\n)?/gm;

/** A CommonMark fence line: up to 3 spaces, then 3+ backticks or tildes. */
const FENCE_RE = /^ {0,3}(`{3,}|~{3,})/;

/** A markdown inline link whose target is relative (no scheme, no `#`, no `/`). */
const RELATIVE_LINK_RE = /\]\((?![a-z][a-z0-9+.-]*:|#|\/)([^)\s]+)\)/gi;

/**
 * The header `style-gen init` writes above the contract.
 * @param {string} version - `package.json#version` of the build
 * @returns {string} Two HTML comment lines and a blank line
 */
export function agentRulesHeader(version) {
  return [
    `<!-- @duydpdev/style-generator ${version} — generated by style-gen init; do not edit, run \`style-gen init --rules-only\` after upgrading -->`,
    '<!-- Tailwind scans this file: keep `@source not "<path to .claude>";` next to `@import "tailwindcss";` (style-gen init prints it). -->',
    "",
  ].join("\n");
}

/**
 * Turn the contract markdown into the shipped rules file.
 * @param {string} markdown - `documents/agent-contract.md`, embeds filled
 * @param {string} version - `package.json#version` of the build
 * @param {string} [fromRepoPath] - The contract's repo path, for resolving links
 * @returns {string} The rules file content
 * @throws {Error} When a fenced block is left unclosed (the markers would be ambiguous)
 */
export function toAgentRules(
  markdown,
  version,
  fromRepoPath = "documents/agent-contract.md",
) {
  const blob = `${REPO_BLOB_URL}v${version}/`;
  const prose = (text) =>
    text
      .replace(MARKER_LINE_RE, "")
      .replace(RELATIVE_LINK_RE, (_match, href) => {
        const url = new URL(href, `https://repo.invalid/${fromRepoPath}`);
        return `](${blob}${url.pathname.slice(1)}${url.hash})`;
      });
  return `${agentRulesHeader(version)}\n${mapProse(markdown, prose)}`;
}

/**
 * Apply `transform` to the text outside fenced blocks; fenced blocks are
 * copied byte for byte. A fence closes on a line of the same character, at
 * least as long, and nothing else (CommonMark), so a fence of 4 backticks
 * or of tildes may hold a block fenced with 3 backticks.
 * @param {string} markdown - The markdown source
 * @param {(text: string) => string} transform - Rewrites a run of prose
 * @returns {string} The markdown with every prose run transformed
 * @throws {Error} When a fenced block is left unclosed
 */
function mapProse(markdown, transform) {
  const lines = markdown.split(/(?<=\n)/);
  let out = "";
  let prose = "";
  /** @type {string | undefined} */
  let fence;
  for (const line of lines) {
    const run = FENCE_RE.exec(line)?.[1];
    if (fence === undefined) {
      if (run === undefined) {
        prose += line;
        continue;
      }
      out += transform(prose);
      prose = "";
      fence = run;
      out += line;
      continue;
    }
    out += line;
    const closes =
      run !== undefined &&
      run[0] === fence[0] &&
      run.length >= fence.length &&
      line.trim() === run;
    if (closes) fence = undefined;
  }
  if (fence !== undefined) {
    throw new Error("agent-rules: unclosed fenced block in the contract");
  }
  return out + transform(prose);
}
