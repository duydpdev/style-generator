import * as prettier from "prettier";
import { describe, expect, it } from "vitest";

import { renderTokensModule } from "./tokensModule";

const web = { typography: ["heading1"], colors: ["primary", "surface"] };

const expected = `// Generated by @duydpdev/style-generator. Do not edit: run \`style-gen generate\`.
// prettier-ignore
export const tokens = {
  "typography": [
    "heading1"
  ],
  "colors": [
    "primary",
    "surface"
  ]
} as const;
// prettier-ignore
export type Tokens = typeof tokens;
// prettier-ignore
export const themeAxes = {
  "theme": [
    "dark"
  ],
  "palette": [
    "forest"
  ]
} as const;
// prettier-ignore
export type ThemeAxesState = {
  readonly [A in keyof typeof themeAxes]?: (typeof themeAxes)[A][number] | "base";
};
`;

describe("renderTokensModule", () => {
  it("renders the tokens and both axes byte for byte", () => {
    expect(
      renderTokensModule(web, {
        theme: { dark: { colors: { primary: "#000" } } },
        palette: { forest: { colors: { primary: "#0a0" } } },
      }),
    ).toBe(expected);
  });

  it("renders an empty themeAxes object when the theme has no axes", () => {
    const withoutAxes = renderTokensModule(web, undefined);

    expect(withoutAxes).toContain("export const themeAxes = {} as const;");
    expect(renderTokensModule(web, {})).toBe(withoutAxes);
  });

  it("is left unchanged by Prettier", async () => {
    const source = renderTokensModule(web, {
      theme: { dark: {} },
      palette: { forest: {} },
    });

    await expect(
      prettier.check(source, { parser: "typescript" }),
    ).resolves.toBe(true);
  });
});
