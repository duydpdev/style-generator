import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import { describe, expect, it } from "vitest";

const moduleUrl = pathToFileURL(
  join(__dirname, "..", "..", "scripts", "agent-rules.mjs"),
).href;

/**
 * Run `toAgentRules` in a Node child process (the script is plain ESM).
 * @param {string} markdown - Contract markdown
 * @param {string} version - Package version to stamp
 * @returns {{ ok?: string, error?: string }} The output, or the thrown message
 */
function convert(
  markdown: string,
  version = "9.9.9",
): { ok?: string; error?: string } {
  const code = [
    `import { toAgentRules } from ${JSON.stringify(moduleUrl)};`,
    "let result;",
    `try { result = { ok: toAgentRules(${JSON.stringify(markdown)}, ${JSON.stringify(version)}) }; }`,
    "catch (error) { result = { error: error.message }; }",
    "process.stdout.write(JSON.stringify(result));",
  ].join("\n");
  const run = spawnSync(process.execPath, ["--input-type=module", "-e", code], {
    encoding: "utf8",
  });
  return JSON.parse(run.stdout) as { ok?: string; error?: string };
}

/** Links point at the tag of the stamped version (`convert` stamps 9.9.9). */
const BLOB = "https://github.com/duydpdev/style-generator/blob/v9.9.9/";

describe("integration: toAgentRules", () => {
  it("stamps the version on the first line and adds the @source not hint", () => {
    const lines = (convert("# Title\n", "7.1.0").ok ?? "").split("\n");
    expect(lines[0]).toBe(
      "<!-- @duydpdev/style-generator 7.1.0 — generated by style-gen init; do not edit, run `style-gen init --rules-only` after upgrading -->",
    );
    expect(lines[1]).toContain('@source not "<path to .claude>";');
    expect(lines.slice(2)).toEqual(["", "# Title", ""]);
  });

  it("drops docs-script markers but keeps the fenced block they filled", () => {
    const md =
      "Intro:\n\n<!-- embed: examples/a.ts#r -->\n\n```ts\nconst a = 1;\n```\n\n<!-- signature: X -->\n\n```ts\ndeclare const x: 1;\n```\n\n<!-- /signature -->\n\nEnd.\n";
    const body = (convert(md).ok ?? "").split("\n").slice(3).join("\n");
    expect(body).toBe(
      "Intro:\n\n```ts\nconst a = 1;\n```\n\n```ts\ndeclare const x: 1;\n```\n\nEnd.\n",
    );
  });

  it("rewrites relative links to GitHub blob URLs and leaves others alone", () => {
    const md =
      "[a](./components.md) [b](./reference/ui.md#pick) [c](../README.md) [d](#local) [e](https://x.dev/y)\n";
    expect(convert(md).ok).toContain(
      `[a](${BLOB}documents/components.md) [b](${BLOB}documents/reference/ui.md#pick) [c](${BLOB}README.md) [d](#local) [e](https://x.dev/y)`,
    );
  });

  it("never touches markers or links inside a fenced block", () => {
    const fence =
      "```md\n<!-- embed: examples/a.ts -->\n[a](./components.md)\n```\n";
    expect(convert(fence).ok?.endsWith(fence)).toBe(true);
  });

  it("keeps ~~~ and longer backtick fences whole, a ``` block inside included", () => {
    const tilde = "~~~md\n[a](./components.md)\n```\n<!-- embed: x -->\n~~~\n";
    const long =
      "````md\n```ts\n<!-- embed: examples/a.ts -->\n```\n[a](./components.md)\n````\n";
    const md = `${tilde}\n${long}\n[b](./components.md)\n`;
    expect(
      convert(md).ok?.endsWith(md.replace("[b](./", `[b](${BLOB}documents/`)),
    ).toBe(true);
  });

  it("closes a fence only on the same character, at least as long", () => {
    const md = "````\n```\n~~~~\n````\n[a](./components.md)\n";
    expect(convert(md).ok).toContain(
      `\`\`\`\`\n[a](${BLOB}documents/components.md)\n`,
    );
  });

  it("fails on an unclosed fence", () => {
    expect(convert("```ts\nconst a = 1;\n").error).toMatch(/unclosed fenced/);
    expect(convert("````md\n```\n").error).toMatch(/unclosed fenced/);
  });

  it("leaves no marker or relative link in the real contract", () => {
    const contract = readFileSync(
      join(__dirname, "..", "..", "documents", "agent-contract.md"),
      "utf8",
    );
    const out = convert(contract).ok ?? "";
    expect(out).not.toMatch(/<!-- \/?(?:embed|signature|snippet)\b/);
    expect(out).not.toMatch(/\]\((?!https?:|#)/);
    expect(out).toContain("export const cn = createCn(tokens);");
  });
});
